// образцу hoursTokens/historyTokens/timelineTokens/entryTokens.
//
// Почему не общие COLORS: `COLORS.border` (#e2e8f0) и `COLORS.muted`
// (#94a3b8) рассчитаны на разделители и второстепенный текст на карточках,
// и на графике вся картинка из них выцветала в почти-белое — владелец
// прислал референс с заметно более контрастной сеткой, тёмными подписями
// и насыщенной индиго-линией. Здесь эти роли разведены явно, чтобы
// «поднять контраст графика» больше не означало «поменять COLORS.border
// всему приложению».
// TASK_078 — live light/dark pair (src/theme/scheme.ts).
import { live } from "@/theme/scheme";

export const CHART_LIGHT = {
  // Линия факта — насыщенная индиго (indigo-800), как на референсе.
  // Остаётся в рамках «фирменной синей/индиго» палитры Ministry
  // (ср. TALK_CATEGORY.dot #6366f1).
  fact: "#3730a3",
  // Заливка полых маркеров на днях реального изменения.
  markerFill: "#ffffff",
  // Идеальный темп — светлый индиго-200: видимый пунктир, но он никогда
  // не спорит с линией факта за внимание.
  ideal: "#c7d2fe",
  // Крайние деления шкалы (0 и верх) читаются как оси.
  axis: "#94a3b8",
  // Промежуточные горизонтальные линии и ежедневная вертикальная сетка.
  grid: "#cbd5e1",
  // Подписи осей и легенды — slate-700 вместо прежнего светло-серого.
  label: "#334155",
};
// Тёмная тема: индиго светлее (indigo-400) на графитовой карточке, сетка и
// оси — белые с малой прозрачностью, подписи — slate-300.
export const CHART_DARK: typeof CHART_LIGHT = {
  fact: "#818cf8",
  markerFill: "#1c2029",
  ideal: "#3f3f8f",
  axis: "rgba(255,255,255,0.28)",
  grid: "rgba(255,255,255,0.12)",
  label: "#cbd5e1",
};
export const CHART = live(CHART_LIGHT, CHART_DARK);

